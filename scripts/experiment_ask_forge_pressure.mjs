// Natural structural units per artifact: each array member is one object, and
// each named evidence-bearing field counts as one.
const OBJECT_ARRAYS = [
  "relevant_implementation_surfaces",
  "gaps",
  "non_blocking_verifications",
  "derived_implementation_impact",
  "human_decisions",
  "implementation_surfaces",
  "delegated_verifications",
  "conflicts",
];
const OBJECT_FIELDS = ["observed_current_behavior", "authority_boundary", "approved_target", "handoff_note", "authority_boundary_applied"];

function countObjects(artifact) {
  if (typeof artifact === "string") return 1;
  let count = 0;
  for (const key of OBJECT_ARRAYS) if (Array.isArray(artifact[key])) count += artifact[key].length;
  for (const key of OBJECT_FIELDS) if (artifact[key] != null) count += 1;
  return count;
}

function artifactMetrics(artifacts, syntheticIds) {
  let bytes = 0;
  let objects = 0;
  for (const [, artifact] of Object.entries(artifacts)) {
    bytes += Buffer.byteLength(JSON.stringify(artifact), "utf8");
    objects += countObjects(artifact);
  }
  const synthetic = syntheticIds.size;
  return {
    artifact_bytes: bytes,
    object_count: objects,
    relevant_object_count: objects - synthetic,
    synthetic_object_count: synthetic,
    relevant_ratio: objects ? Number(((objects - synthetic) / objects).toFixed(3)) : null,
  };
}

// ---------------------------------------------------------------------------
// locator resolution — separates the four properties the report distinguishes:
// syntactic form, retrieval membership, locator existence, target identity.
// ---------------------------------------------------------------------------

function collectIds(node, path, out) {
  if (Array.isArray(node)) {
    node.forEach((item, index) => collectIds(item, `${path}[${index}]`, out));
  } else if (node && typeof node === "object") {
    if (typeof node.id === "string") out.set(node.id, node);
    for (const [key, value] of Object.entries(node)) collectIds(value, path ? `${path}.${key}` : key, out);
  }
}

function walk(root, locator) {
  let node = root;
  for (const token of locator.split(".")) {
    const match = token.match(/^([^[\]]*)((\[\d+\])*)$/);
    if (!match) return undefined;
    if (match[1]) {
      if (!node || typeof node !== "object" || !(match[1] in node)) return undefined;
      node = node[match[1]];
    }
    for (const index of match[2].match(/\d+/g) || []) {
      if (!Array.isArray(node)) return undefined;
      node = node[Number(index)];
    }
    if (node === undefined) return undefined;
  }
  return node;
}

function resolveLocator(artifact, locator) {
  if (typeof artifact === "string") return { exists: locator === "", node: null };
  if (locator === "") return { exists: false, node: null };
  const ids = new Map();
  collectIds(artifact, "", ids);
  if (ids.has(locator)) return { exists: true, node: ids.get(locator), viaId: locator };
  for (const [id, node] of ids) {
    if (locator.startsWith(`${id}.`)) {
      const child = walk(node, locator.slice(id.length + 1));
      return { exists: child !== undefined, node, viaId: id };
    }
  }
  const node = walk(artifact, locator);
  return { exists: node !== undefined, node: node && typeof node === "object" ? node : null };
}

// A citation points at a synthetic object when the object it resolves to — or
// any object it is nested in — carries a stress-fixture id.
function isSynthetic(node, syntheticIds) {
  if (!node || typeof node !== "object") return false;
  if (typeof node.id === "string" && syntheticIds.has(node.id)) return true;
  if (typeof node.surface_ref === "string" && syntheticIds.has(node.surface_ref)) return true;
  if (typeof node.gap_ref === "string" && syntheticIds.has(node.gap_ref)) return true;
  return false;
}

function scoreCitations(artifacts, retrieved, evidence, syntheticIds) {
  const report = [];
  for (const citation of evidence) {
    const hash = citation.indexOf("#");
    const file = hash === -1 ? citation : citation.slice(0, hash);
    const locator = hash === -1 ? "" : citation.slice(hash + 1);
    const inRetrieval = retrieved.includes(file);
    const artifact = artifacts[file];
    const resolved = artifact !== undefined ? resolveLocator(artifact, locator) : { exists: false, node: null };
    report.push({
      citation,
      syntactic_valid: hash > 0 && locator.length > 0,
      retrieval_member: inRetrieval,
      locator_exists: Boolean(inRetrieval && resolved.exists),
      points_to_synthetic: isSynthetic(resolved.node, syntheticIds),
    });
  }
  return {
    details: report,
    citation_count: report.length,
    valid_citation_count: report.filter((r) => r.retrieval_member && r.locator_exists).length,
    nonexistent_locator_count: report.filter((r) => r.retrieval_member && !r.locator_exists).length,
    out_of_retrieval_count: report.filter((r) => !r.retrieval_member).length,
    irrelevant_citation_count: report.filter((r) => r.points_to_synthetic).length,
  };
}

