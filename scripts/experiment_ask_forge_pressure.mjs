function projectOf(requirementId) {
  return requirementId.startsWith("outline") ? "outline" : "petclinic";
}

function repoOf(requirementId) {
  return projectOf(requirementId) === "outline" ? OUTLINE_REPO : PETCLINIC_REPO;
}

function makeSurface(template, revision, repo, suffix) {
  const [id, layer, description, type, path] = template;
  const finalId = suffix ? `${id}_${suffix}` : id;
  return {
    id: finalId,
    layer,
    description,
    evidence: {
      type,
      path,
      source: `${repo}/blob/${revision}/${path}`,
      note: description,
    },
  };
}

// Grows project_context surfaces (and the mirrored package surfaces) by a
// multiplier, leaving the blocking `gaps` array untouched so the human_decision
// ground truth stays fixed while the artifact around it grows.
function applySizePressure(requirementId, artifacts, multiplier) {
  const context = artifacts["project_context.json"];
  const original = context.relevant_implementation_surfaces.length;
  const wanted = Math.max(0, Math.round(original * multiplier) - original);
  const pool = IRRELEVANT_TEMPLATES[projectOf(requirementId)];
  const revision = context.reference_revision;
  const repo = repoOf(requirementId);
  const syntheticIds = new Set();
  for (let index = 0; index < wanted; index += 1) {
    const template = pool[index % pool.length];
    const round = Math.floor(index / pool.length);
    const surface = makeSurface(template, revision, repo, round ? String(round + 1).padStart(2, "0") : "");
    context.relevant_implementation_surfaces.push(surface);
    syntheticIds.add(surface.id);
    const pkg = artifacts["implementation_package.json"];
    if (Array.isArray(pkg.implementation_surfaces)) {
      pkg.implementation_surfaces.push({ surface_ref: surface.id, change: "変更なし — この要件では触れません。" });
    }
    const gaps = artifacts["gaps.json"];
    if (Array.isArray(gaps.derived_implementation_impact)) {
      gaps.derived_implementation_impact.push({
        id: `derived.${surface.id.split(".").pop()}`,
        surface_ref: surface.id,
        note: "承認された振る舞いから導かれる実装上の影響はありません。",
      });
      syntheticIds.add(`derived.${surface.id.split(".").pop()}`);
    }
  }
  return syntheticIds;
}

function applySimilarityPressure(requirementId, artifacts) {
  const context = artifacts["project_context.json"];
  const revision = context.reference_revision;
  const repo = repoOf(requirementId);
  const syntheticIds = new Set();
  for (const template of SIMILAR_TEMPLATES[requirementId]) {
    const surface = makeSurface(template, revision, repo, "");
    context.relevant_implementation_surfaces.push(surface);
    syntheticIds.add(surface.id);
  }
  return syntheticIds;
}

