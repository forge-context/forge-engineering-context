const env = await loadEnv();
await initStressRoot();

async function runOnce({ fixtureId, requirementId, artifacts, question, client }) {
  const handleAskRequest = await buildStressLib(fixtureId, registryFor(requirementId, artifacts));
  const store = memoryStore();
  const request = new Request("http://localhost/api/ask", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ requirement_id: requirementId, question }),
  });
  const started = Date.now();
  const response = await handleAskRequest(request, env, { store, cache: noCache, ...(client ? { client } : {}) });
  const body = await response.json();
  const trace = store.audit[store.audit.length - 1] || {};
  return { body, trace, httpStatus: response.status, wallMs: Date.now() - started };
}

