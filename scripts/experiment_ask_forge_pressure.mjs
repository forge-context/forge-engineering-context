// This runner never imports production code from its own location. It copies
// functions/_lib verbatim into a throwaway temporary directory, replaces only
// `artifacts.generated.js` with a stress fixture, and imports the *copy*. The
// production registry, examples/, and the generated bundle are never written.
// Byte-identity of every copied production file is asserted before each run and
// recorded in the report, so "the harness did not change the pipeline" is an
// observed fact rather than a claim.
//
//   node scripts/experiment_ask_forge_pressure.mjs --suites=baseline,A,B,C,D,E
//   node scripts/experiment_ask_forge_pressure.mjs --suites=A --repeat=3 --only=A3-OC-B
