let stressRoot = null;
const productionHashes = {};
const copyProof = [];

async function initStressRoot() {
  stressRoot = await mkdtemp(join(tmpdir(), "ask-forge-pressure-"));
  for (const name of await readdir(LIB_DIR)) {
    productionHashes[name] = sha(await readFile(join(LIB_DIR, name), "utf8"));
  }
}

// Builds one isolated module tree. Every production file except the generated
// artifact registry is copied byte-for-byte and re-hashed after the copy.
async function buildStressLib(fixtureId, registry) {
  const dir = join(stressRoot, fixtureId);
  await mkdir(dir, { recursive: true });
  const verified = [];
  for (const name of await readdir(LIB_DIR)) {
    if (name === GENERATED) continue;
    await cp(join(LIB_DIR, name), join(dir, name));
    const after = sha(await readFile(join(dir, name), "utf8"));
    if (after !== productionHashes[name]) throw new Error(`copy of ${name} is not byte-identical`);
    verified.push(name);
  }
  const serialized = JSON.stringify({ requirements: registry.requirements, shared: registry.shared }, null, 2);
  const revision = sha(serialized).slice(0, 16);
  await writeFile(
    join(dir, GENERATED),
    [
      "// Stress fixture generated by scripts/experiment_ask_forge_pressure.mjs. Experiment only.",
      `export const ARTIFACTS_REVISION = ${JSON.stringify(revision)};`,
      `export const DEFAULT_REQUIREMENT_ID = ${JSON.stringify(registry.defaultRequirementId)};`,
      `export const REQUIREMENT_ARTIFACT_NAMES = ${JSON.stringify(registry.artifactNames)};`,
      `export const REQUIREMENTS = ${JSON.stringify(registry.requirements, null, 2)};`,
      `export const SHARED_ARTIFACTS = ${JSON.stringify(registry.shared, null, 2)};`,
      "",
    ].join("\n"),
    "utf8",
  );
  copyProof.push({ fixture: fixtureId, verbatim_copies: verified, replaced: [GENERATED] });
  const { handleAskRequest } = await import(pathToFileURL(join(dir, "service.js")).href);
  return handleAskRequest;
}

