import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sources = {
  "project_context.json": "examples/petclinic/project_context.json",
  "gaps.json": "examples/petclinic/gaps.json",
  "implementation_package.json": "examples/petclinic/implementation_package.json",
  "architecture.md": "docs/architecture.md",
};

const artifacts = {};
for (const [name, relativePath] of Object.entries(sources)) {
  const text = await readFile(resolve(repoRoot, relativePath), "utf8");
  artifacts[name] = name.endsWith(".json") ? JSON.parse(text) : text;
}

const outputPath = resolve(repoRoot, "functions/_lib/artifacts.generated.js");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/generate_public_artifacts.mjs. Do not edit directly.\nexport const ARTIFACTS = ${JSON.stringify(artifacts, null, 2)};\n`,
  "utf8",
);
